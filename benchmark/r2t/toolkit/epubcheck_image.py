def _window_utc() -> str:
    return _datetime.datetime.now(_datetime.timezone.utc).isoformat().replace("+00:00", "Z")


def _base_phase(session: CommandSession, gates: SourceGates,
                authority: Mapping[str, object], observer: PullObserver,
                before: dict, revalidate: Callable[[], Mapping[str, object]],
                output: PrivateOutput) -> tuple[dict, dict, dict]:
    expected = base_reference(gates)
    for image_id in before["images"]:
        result = session.docker(("image", "inspect", image_id, "--format",
                                 "{{json .}}"), timeout=30)
        document = _json_object(result.stdout, "pre-pull image inspect")
        if set(base_repo_digest_references(gates)).intersection(
                document.get("RepoDigests") or []):
            raise PhaseFailure("refused_before_effect",
                               "approved base digest already exists before first pull")
    absent = session.docker(("image", "inspect", CONVENIENCE_TAG), timeout=30,
                            check=False)
    _require_absent_inspect(absent, "convenience tag before first pull")
    observer.start(authority)
    pull_result = None
    observation = None
    try:
        try:
            pull_result = session.docker(base_pull_argv(gates), timeout=1800)
        finally:
            observation = observer.stop()
        revalidate()
        observed_redirect = discover_pull_redirect(observation)
        inspected = session.docker(("image", "inspect", expected, "--format",
                                    "{{json .}}"), timeout=30)
        document = _json_object(inspected.stdout, "pulled base inspect")
        image_id, repo_digest = _base_inspect(document, gates)
        image_artifact = output.write_raw("image.json", inspected.stdout)
        after = inspected_inventory(session)
        _inventory_unchanged_except(before, after, added_images=(image_id,))
        result = {
            "base_reference": expected, "base_config_id": image_id,
            "base_repo_digest": repo_digest,
            "observed_redirect_host": observed_redirect,
            "observer": {
                "dns_hosts": list(observation.dns_hosts),
                "connections": [[host, port]
                                for host, port in observation.connections],
                "resolver_addresses": list(observation.resolver_addresses),
                "dropped_events": observation.dropped_events,
                "unknown_redirect_prevented": observation.unknown_redirect_prevented,
            },
            "pull_stdout_sha256": hashlib.sha256(pull_result.stdout).hexdigest(),
            "image_json_sha256": image_artifact["sha256"],
            "image_json_size": image_artifact["size"],
        }
    except Exception:
        # Only a zero-status pull can join a new exact digest strongly enough
        # for automatic rollback.  A timeout/launch failure remains manual.
        if pull_result is not None and pull_result.returncode == 0:
            with contextlib.suppress(Exception):
                revalidate()
                inspected = session.docker((
                    "image", "inspect", expected, "--format", "{{json .}}"),
                    timeout=30, check=False)
                if inspected.returncode == 0:
                    document = _json_object(
                        inspected.stdout, "failed pulled base inspect")
                    image_id, _repo_digest = _base_inspect(document, gates)
                    current = inspected_inventory(session)
                    _inventory_unchanged_except(
                        before, current, added_images=(image_id,))
                    session.docker(("image", "rm", image_id), timeout=60)
        raise
    cleanup = {"retained_images": [image_id], "removed_images": [],
               "leftovers": []}
    return result, after, cleanup


