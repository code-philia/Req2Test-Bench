def discover_pull_redirect(value: PullObservation) -> str:
    """Validate the candid first-pull record and return its one unknown host."""
    if not isinstance(value, PullObservation) \
            or not isinstance(value.dropped_events, int) \
            or isinstance(value.dropped_events, bool) \
            or value.dropped_events != 0:
        raise _refuse("R-1 observer dropped events")
    if value.unknown_redirect_prevented is not False:
        raise _refuse("R-1 evidence falsely claims pre-connect redirect enforcement")
    known = {"auth.docker.io", "registry-1.docker.io"}
    if not isinstance(value.dns_hosts, tuple) or not value.dns_hosts \
            or any(not isinstance(host, str) or _DNS_HOST.fullmatch(host) is None
                   for host in value.dns_hosts):
        raise _refuse("R-1 DNS observation is malformed")
    hosts = set(value.dns_hosts)
    extras = hosts - known
    if len(extras) != 1:
        raise _refuse(
            "R-1 first pull did not observe exactly the known hosts plus one redirect")
    redirect = next(iter(extras))
    if _DNS_HOST.fullmatch(redirect) is None or redirect in {
            CENTRAL_HOST, "repo1.maven.org", "index.docker.io"}:
        raise _refuse("observed R-1 redirect host is malformed or not distinct")
    required = known | {redirect}
    if hosts != required:
        raise _refuse("R-1 first pull is missing a required Docker Hub DNS host")
    if not isinstance(value.connections, tuple) or not value.connections:
        raise _refuse("R-1 connection observation is malformed")
    normalized_connections = []
    for connection in value.connections:
        if not isinstance(connection, tuple) or len(connection) != 2:
            raise _refuse("R-1 connection observation is malformed")
        host, port = connection
        if not isinstance(host, str) or not isinstance(port, int) \
                or isinstance(port, bool) or port != 443 \
                or _DNS_HOST.fullmatch(host) is None:
            raise _refuse("R-1 connection is malformed or non-443")
        if re.fullmatch(r"[0-9a-fA-F:.]+", host):
            raise _refuse("R-1 connection is recorded as a literal IP")
        normalized_connections.append((host, port))
    if set(normalized_connections) != {(host, 443) for host in required}:
        raise _refuse("R-1 connections are incomplete or name another host")
    if not isinstance(value.resolver_addresses, tuple) \
            or any(not isinstance(item, str) or not item
                   for item in value.resolver_addresses):
        raise _refuse("R-1 resolver observation is malformed")
    return redirect


def _json_object(raw: bytes, label: str) -> dict:
    def exact_object(pairs: list[tuple[str, object]]) -> dict:
        value = {}
        for key, item in pairs:
            if key in value:
                raise ValueError("duplicate JSON key")
            value[key] = item
        return value

    try:
        value = json.loads(raw.decode("utf-8"), object_pairs_hook=exact_object)
    except (UnicodeDecodeError, json.JSONDecodeError, ValueError) as exc:
        raise PhaseFailure("identity_mismatch", f"{label} is not exact JSON") from exc
    if isinstance(value, list) and len(value) == 1:
        value = value[0]
    if not isinstance(value, dict):
        raise PhaseFailure("identity_mismatch", f"{label} is not one object")
    return value


def _created_object_id(raw: bytes, label: str) -> str:
    """Parse Docker create's one exact immutable-ID stdout line."""
    try:
        text = raw.decode("ascii")
    except UnicodeDecodeError as exc:
        raise PhaseFailure(
            "identity_mismatch", f"{label} create stdout is not ASCII") from exc
    if re.fullmatch(r"[0-9a-f]{64}\n", text) is None:
        raise PhaseFailure(
            "identity_mismatch",
            f"{label} create stdout is not one lower-case immutable ID")
    return text[:-1]


def _docker_label_map(document: Mapping[str, object], category: str) -> dict[str, str]:
    """Return one authenticated Docker label map for an inventory object."""
    if category in {"images", "containers"}:
        config = document.get("Config")
        if not isinstance(config, dict):
            raise PhaseFailure(
                "identity_mismatch", f"Docker {category} Config is malformed")
        labels = config.get("Labels")
    elif category in {"networks", "volumes"}:
        labels = document.get("Labels")
    else:
        raise AssertionError(category)
    if labels is None:
        return {}
    if not isinstance(labels, dict) \
            or any(not isinstance(key, str) or not isinstance(value, str)
                   for key, value in labels.items()):
        raise PhaseFailure(
            "identity_mismatch", f"Docker {category} Labels is malformed")
    return labels


def _canonical_digest(value: object) -> str:
    raw = json.dumps(value, sort_keys=True, separators=(",", ":"),
                     ensure_ascii=True).encode("ascii")
    return hashlib.sha256(raw).hexdigest()


class CommandSession:
    """One phase's exact Docker calls, raw streams, and authority ordering."""

    def __init__(self, runner: DockerRunner, output: PrivateOutput,
                 revalidate: Callable[[], Mapping[str, object]]):
        self.runner = runner
        self.output = output
        self.revalidate = revalidate
        self._commands: list[tuple[int, dict]] = []
        self._number = 0
        self.effect_attempted = False
        self._io_lock = threading.Lock()

    def _stream_evidence(self, name: str, raw: bytes) -> dict:
        """Bind an empty stream in JSON without creating an empty raw file."""
        if raw:
            return self.output.write_raw(name, raw)
        return {"name": None, "size": 0,
                "sha256": hashlib.sha256(b"").hexdigest()}

    def _record_runner_exception(self, number: int, inner: tuple[str, ...],
                                 *, timeout: int, build: bool,
                                 stream: bool) -> None:
        """Preserve invocation order when the client cannot return a result."""
        empty = {"name": None, "size": 0,
                 "sha256": hashlib.sha256(b"").hexdigest()}
        record = {
            "kind": "docker-stream" if stream else "docker",
            "argv": list(inner), "timeout_seconds": timeout,
            "environment": clean_subprocess_environment(build=build),
            # 125 is Docker's conventional client-side invocation failure.
            # It records no invented stdout/stderr bytes.
            "returncode": 125, "timed_out": False, "overflowed": False,
            "stderr": dict(empty),
        }
        if stream:
            record.update({"stream_size": 0,
                           "stream_sha256": hashlib.sha256(b"").hexdigest()})
        else:
            record["stdout"] = dict(empty)
            if inner[:2] in {("container", "create"), ("network", "create")}:
                record["created_id"] = None
        with self._io_lock:
            self._commands.append((number, record))

    @property
    def commands(self) -> list[dict]:
        """Invocation-ordered records even when a build is monitored in parallel."""
        with self._io_lock:
            return [record for _number, record in sorted(self._commands)]

    def docker(self, argv: Sequence[str], *, timeout: int,
               build: bool = False, check: bool = True,
               cancel: Optional[threading.Event] = None) -> CommandResult:
        inner = validate_docker_inner_argv(argv)
        if docker_is_mutation(inner):
            self.effect_attempted = True
            self.revalidate()
        with self._io_lock:
            self._number += 1
            number = self._number
        try:
            result = self.runner.run(
                inner, timeout=timeout, build=build, cancel=cancel)
        except Exception:
            self._record_runner_exception(
                number, inner, timeout=timeout, build=build, stream=False)
            raise
        create_command = inner[:2] in {
            ("container", "create"), ("network", "create")}
        created_id: Optional[str] = None
        create_error: Optional[PhaseFailure] = None
        if create_command and result.returncode == 0 \
                and not result.timed_out and not result.overflowed:
            try:
                created_id = _created_object_id(
                    result.stdout, inner[0] + " create")
            except PhaseFailure as exc:
                create_error = exc
        with self._io_lock:
            stdout_name = f"docker-{number:04d}.stdout"
            stderr_name = f"docker-{number:04d}.stderr"
            stdout = self._stream_evidence(stdout_name, result.stdout)
            stderr = self._stream_evidence(stderr_name, result.stderr)
            record = {
                "kind": "docker", "argv": list(inner),
                "timeout_seconds": timeout,
                "environment": clean_subprocess_environment(build=build),
                "returncode": result.returncode, "timed_out": result.timed_out,
                "overflowed": result.overflowed,
                "stdout": stdout, "stderr": stderr,
            }
            if create_command:
                record["created_id"] = created_id
            self._commands.append((number, record))
        if result.timed_out:
            self.revalidate()
            raise PhaseFailure("cleanup_unconfirmed", "Docker client timed out; no retry")
        if result.overflowed:
            self.revalidate()
            raise PhaseFailure("cleanup_unconfirmed", "Docker log exceeded 64 MiB")
        if check and result.returncode != 0:
            raise PhaseFailure("docker_failure",
                               f"Docker command returned {result.returncode}")
        if create_error is not None:
            raise create_error
        return result

    def docker_stream(self, argv: Sequence[str], *, timeout: int,
                      target: str, maximum: int) -> StreamResult:
        inner = validate_docker_inner_argv(argv)
        if docker_is_mutation(inner):
            self.effect_attempted = True
            self.revalidate()
        with self._io_lock:
            self._number += 1
            number = self._number
        try:
            result = self.runner.stream_to(
                inner, timeout=timeout, target=target, maximum=maximum)
        except Exception:
            self._record_runner_exception(
                number, inner, timeout=timeout, build=False, stream=True)
            raise
        with self._io_lock:
            stderr_name = f"docker-{number:04d}.stderr"
            stderr = self._stream_evidence(stderr_name, result.stderr)
            # The streamed payload is deliberately not retained as a transcript
            # raw log.  Its complete size/digest are recorded in this command row;
            # an empty stdout placeholder would violate the compact-evidence rule.
            self._commands.append((number, {
                "kind": "docker-stream", "argv": list(inner),
                "timeout_seconds": timeout,
                "environment": clean_subprocess_environment(),
                "returncode": result.returncode, "timed_out": result.timed_out,
                "overflowed": result.overflowed, "stderr": stderr,
                "stream_size": result.size,
                "stream_sha256": result.sha256,
            }))
        if result.timed_out or result.overflowed:
            self.revalidate()
            raise PhaseFailure("cleanup_unconfirmed",
                               "Docker repository stream timed out/overflowed")
        if result.returncode != 0:
            raise PhaseFailure("docker_failure", "Docker repository stream failed")
        return result


def inspected_inventory(
        session: CommandSession, *,
        refuse_attempt_label: Optional[str] = None) -> dict:
    """Capture complete image/container/network/volume identities by inspect."""
    if refuse_attempt_label is not None \
            and _ATTEMPT_ID.fullmatch(refuse_attempt_label) is None:
        raise PhaseFailure("identity_mismatch", "attempt label is malformed")
    list_commands = {
        "images": ("image", "ls", "--all", "--no-trunc", "--quiet"),
        "containers": ("container", "ls", "--all", "--no-trunc", "--quiet"),
        "networks": ("network", "ls", "--no-trunc", "--quiet"),
        "volumes": ("volume", "ls", "--quiet"),
    }
    inspect_heads = {
        "images": ("image", "inspect"),
        "containers": ("container", "inspect"),
        "networks": ("network", "inspect"),
        "volumes": ("volume", "inspect"),
    }
    inventory = {}
    for category in ("images", "containers", "networks", "volumes"):
        listed = session.docker(list_commands[category], timeout=30)
        try:
            text = listed.stdout.decode("ascii")
        except UnicodeDecodeError as exc:
            raise PhaseFailure("identity_mismatch",
                               f"Docker {category} list is not ASCII") from exc
        raw_names = [line.strip() for line in text.splitlines() if line.strip()]
        names = sorted(set(raw_names))
        # One image config may legitimately have several repository tags, so
        # `image ls --quiet` can repeat its immutable ID.  Other inventories
        # have one list row per object and a duplicate is ambiguous.
        if category != "images" and len(names) != len(raw_names):
            raise PhaseFailure("identity_mismatch", f"Docker {category} list repeats an ID")
        entries = {}
        for name in names:
            if "\x00" in name or name.startswith("-"):
                raise PhaseFailure("identity_mismatch", "Docker inventory ID is malformed")
            result = session.docker((*inspect_heads[category], name,
                                     "--format", "{{json .}}"), timeout=30)
            document = _json_object(result.stdout, f"Docker {category} inspect")
            if category == "volumes":
                identity = document.get("Name")
            else:
                identity = document.get("Id")
            if not isinstance(identity, str) or not identity:
                raise PhaseFailure("identity_mismatch",
                                   f"Docker {category} inspect has no identity")
            if category != "volumes" and name != identity:
                # `image ls --quiet` and container/network IDs are immutable
                # full IDs under --no-trunc; a mismatch is a concurrent change.
                raise PhaseFailure("identity_mismatch",
                                   f"Docker {category} list/inspect identity changed")
            labels = _docker_label_map(document, category)
            if refuse_attempt_label is not None \
                    and labels.get("r2t.attempt") == refuse_attempt_label:
                raise PhaseFailure(
                    "refused_before_effect",
                    f"preexisting Docker {category} object collides with "
                    "the new attempt label")
            entries[identity] = _canonical_digest(document)
        inventory[category] = entries
    return inventory


def _inventory_unchanged_except(before: Mapping[str, object],
                                after: Mapping[str, object], *,
                                added_images: Iterable[str] = ()) -> None:
    added = set(added_images)
    for category in ("containers", "networks", "volumes"):
        if before.get(category) != after.get(category):
            raise PhaseFailure("identity_mismatch",
                               f"unrelated Docker {category} inventory changed")
    before_images = dict(before.get("images", {}))
    after_images = dict(after.get("images", {}))
    if set(after_images) - set(before_images) != added \
            or any(after_images.get(key) != value for key, value in before_images.items()):
        raise PhaseFailure("identity_mismatch",
                           "Docker image inventory changed outside joined attempt IDs")


def _inventory_leftovers(before: Mapping[str, object],
                         after: Mapping[str, object]) -> list[dict]:
    """Return a deterministic immutable-identity delta for failure evidence."""
    leftovers = []
    for category in ("images", "containers", "networks", "volumes"):
        old = dict(before.get(category, {}))
        new = dict(after.get(category, {}))
        for identity in sorted(set(new) - set(old)):
            leftovers.append({"category": category, "identity": identity,
                              "change": "added", "inspect_sha256": new[identity]})
        for identity in sorted(set(old) - set(new)):
            leftovers.append({"category": category, "identity": identity,
                              "change": "removed", "inspect_sha256": old[identity]})
        for identity in sorted(set(old) & set(new)):
            if old[identity] != new[identity]:
                leftovers.append({"category": category, "identity": identity,
                                  "change": "changed",
                                  "before_inspect_sha256": old[identity],
                                  "after_inspect_sha256": new[identity]})
    return leftovers


def _base_inspect(document: Mapping[str, object], gates: SourceGates) -> tuple[str, str]:
    image = dict(document)
    image_id = _image_id(image.get("Id"), "pulled base config ID")
    if image.get("Architecture") != "amd64" or image.get("Os") != "linux":
        raise PhaseFailure("identity_mismatch", "pulled base is not linux/amd64")
    try:
        _validate_image_environment(image.get("Config"), label="pulled base")
    except EPUBCheckImageRefused as exc:
        raise PhaseFailure("identity_mismatch", str(exc)) from exc
    expected_repo_digests = set(base_repo_digest_references(gates))
    repo_digests = image.get("RepoDigests")
    if not isinstance(repo_digests, list) \
            or any(not isinstance(item, str) for item in repo_digests):
        raise PhaseFailure("identity_mismatch", "pulled base RepoDigests are malformed")
    matches = sorted(expected_repo_digests.intersection(repo_digests))
    if not matches:
        raise PhaseFailure("identity_mismatch", "pulled base lacks approved RepoDigest")
    return image_id, matches[0]


def _require_approved_base(session: CommandSession, gates: SourceGates,
                           before: Mapping[str, object]) -> dict:
    approved_id = gates.base_config_id
    if approved_id not in dict(before.get("images", {})):
        raise PhaseFailure("refused_before_effect",
                           "approved base config is absent from pre-inventory")
    inspected = session.docker(("image", "inspect", base_reference(gates),
                                "--format", "{{json .}}"), timeout=30)
    document = _json_object(inspected.stdout, "approved base inspect")
    image_id, _repo_digest = _base_inspect(document, gates)
    if image_id != approved_id:
        raise PhaseFailure("identity_mismatch",
                           "base reference does not join approved config ID")
    by_id = session.docker(("image", "inspect", approved_id or "",
                            "--format", "{{json .}}"), timeout=30)
    if _canonical_digest(_json_object(by_id.stdout, "approved base ID inspect")) \
            != _canonical_digest(document):
        raise PhaseFailure("identity_mismatch",
                           "base reference and approved config inspect differ")
    return document


def _source_commit(repo: str) -> str:
    env = {"LANG": "C", "LC_ALL": "C", "TZ": "UTC",
           "GIT_CONFIG_NOSYSTEM": "1", "GIT_TERMINAL_PROMPT": "0"}
    status = subprocess.run(
        ["git", "-C", repo, "status", "--porcelain=v1", "--untracked-files=all"],
        stdin=subprocess.DEVNULL, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        env=env, timeout=30, check=False)
    if status.returncode != 0 or status.stdout:
        raise _refuse("producer source worktree is not one clean reviewed commit")
    head = subprocess.run(
        ["git", "-C", repo, "rev-parse", "HEAD"], stdin=subprocess.DEVNULL,
        stdout=subprocess.PIPE, stderr=subprocess.PIPE, env=env, timeout=30,
        check=False)
    commit = head.stdout.decode("ascii", "strict").strip() \
        if head.returncode == 0 else ""
    if re.fullmatch(r"[0-9a-f]{40}", commit) is None:
        raise _refuse("producer source commit cannot be authenticated")
    return commit


def _mkdir(path: str, mode: int = 0o700) -> None:
    try:
        os.mkdir(path, mode)
    except OSError as exc:
        raise _refuse(f"cannot create private attempt directory {path!r}: {exc}") from exc
    info = os.lstat(path)
    if not stat.S_ISDIR(info.st_mode) or stat.S_ISLNK(info.st_mode) \
            or info.st_uid != os.getuid() or stat.S_IMODE(info.st_mode) != mode:
        raise _refuse(f"attempt directory is not exact owner-private mode {mode:04o}")


def _write_attempt_file(root: str, rel: str, data: bytes,
                        mode: int = 0o600) -> str:
    if rel.startswith("/") or posixpath.normpath(rel) != rel \
            or rel.startswith("../") or "\x00" in rel:
        raise _refuse("attempt file path is unsafe")
    path = os.path.join(root, *rel.split("/"))
    if os.path.commonpath((root, path)) != root:
        raise _refuse("attempt file parent escapes root")
    current = root
    for component in rel.split("/")[:-1]:
        current = os.path.join(current, component)
        if os.path.lexists(current):
            info = os.lstat(current)
            if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode) \
                    or info.st_uid != os.getuid():
                raise _refuse("attempt file parent is not an owned real directory")
        else:
            _mkdir(current, 0o700)
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL \
        | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0)
    fd = os.open(path, flags, mode)
    try:
        os.fchmod(fd, mode)
        view = memoryview(data)
        while view:
            written = os.write(fd, view)
            view = view[written:]
        os.fsync(fd)
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or stat.S_IMODE(info.st_mode) != mode \
                or info.st_uid != os.getuid():
            raise _refuse("attempt file mode/owner differs after write")
    finally:
        os.close(fd)
    return path


def _attempt_tree(prefix: str) -> dict[str, str]:
    parent = os.lstat(ATTEMPT_PARENT)
    if stat.S_ISLNK(parent.st_mode) or not stat.S_ISDIR(parent.st_mode) \
            or parent.st_uid != os.getuid() \
            or stat.S_IMODE(parent.st_mode) != 0o700:
        raise _refuse("fixed attempt parent is not an owned real 0700 directory")
    root = tempfile.mkdtemp(prefix=prefix, dir=ATTEMPT_PARENT)
    os.chmod(root, 0o700)
    result = {"root": root}
    try:
        for name in ("classes", "helper_source", "config", "cache", "context",
                     "volatile", "prefetch"):
            path = os.path.join(root, name)
            _mkdir(path, 0o700)
            result[name] = path
    except Exception as failure:
        try:
            shutil.rmtree(root)
        except Exception as cleanup_failure:
            raise PhaseFailure(
                "cleanup_unconfirmed",
                "partially created attempt directory could not be removed") \
                from cleanup_failure
        raise
    return result


def _dispose_attempt(paths: Mapping[str, str]) -> None:
    root = paths["root"]
    _absolute(root, "attempt cleanup root")
    if not root.startswith(ATTEMPT_PARENT + "/r2t-epubcheck-image-") \
            or os.path.dirname(root) != ATTEMPT_PARENT:
        raise _refuse("attempt cleanup target is outside the fixed private prefix")
    if os.path.lexists(root):
        shutil.rmtree(root)


def _framed_tree(files: Mapping[str, bytes]) -> str:
    digest = hashlib.sha256()
    digest.update(b"r2t.epubcheck-context/v1\0")
    for path in sorted(files, key=lambda value: value.encode("utf-8")):
        raw = files[path]
        encoded = path.encode("utf-8")
        digest.update(len(encoded).to_bytes(8, "big"))
        digest.update(encoded)
        digest.update(len(raw).to_bytes(8, "big"))
        digest.update(raw)
    return digest.hexdigest()


def _source_context(corpus_root: str, context_root: str,
                    settings: bytes, definition: bytes) -> dict:
    """Reconstruct discovery context from authenticated Git blobs only."""
    from ..java.j0 import (J0Error, build_source_archive_manifest,
                          validate_source_checkout)
    from ..stacks.cucumber import pom_with_coverage
    try:
        manifest = build_source_archive_manifest(PROJECT, corpus_root)
    except J0Error as exc:
        raise _refuse(f"EPUBCheck source authority failed: {exc}") from exc
    entries = {item["path"]: item for item in manifest["files"]}
    selected = [path for path in entries
                if path == "pom.xml" or path.startswith("src/")]
    if "pom.xml" not in selected or not any(path.startswith("src/")
                                             for path in selected):
        raise _refuse("authenticated EPUBCheck tree lacks pom.xml/src")
    files = {}
    for rel in sorted(selected, key=lambda value: value.encode("utf-8")):
        raw = _git_object(corpus_root, CORPUS_COMMIT, rel)
        entry = entries[rel]
        if len(raw) != entry["bytes"] \
                or hashlib.sha256(raw).hexdigest() != entry["raw_file_sha256"]:
            raise _refuse(f"Git blob differs from source manifest: {rel}")
        if rel == "pom.xml":
            try:
                raw = pom_with_coverage(raw.decode("utf-8")).encode("utf-8")
            except (UnicodeDecodeError, RuntimeError) as exc:
                raise _refuse(f"coverage patch refused authenticated pom: {exc}") from exc
        files[rel] = raw
    files[".r2t/settings.xml"] = settings
    files["Dockerfile.discovery"] = definition
    validate_context_paths(files, phase="discovery")
    intended_records = []
    for rel, raw in files.items():
        mode = 0o755 if rel in entries and entries[rel]["git_mode"] == "100755" \
            else 0o644
        _write_attempt_file(context_root, rel, raw, mode)
        intended_records.append(CapturedFile(
            rel, len(raw), hashlib.sha256(raw).hexdigest(), f"{mode:04o}"))
    try:
        validate_source_checkout(PROJECT, corpus_root, manifest)
    except J0Error as exc:
        raise _refuse(f"EPUBCheck source changed during context assembly: {exc}") from exc
    return {"source_manifest": manifest,
            "context_tree_sha256": _framed_tree(files),
            "context_inventory_sha256": _records_tree_sha256(tuple(sorted(
                intended_records, key=lambda item: item.path))),
            "definition_sha256": hashlib.sha256(definition).hexdigest(),
            "pom_sha256": hashlib.sha256(files["pom.xml"]).hexdigest(),
            "paths": sorted(files)}


