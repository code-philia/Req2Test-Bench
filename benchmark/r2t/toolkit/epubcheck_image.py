def _produce(*, phase: str, out: str, gates: SourceGates,
             runner_factory: Callable[[Mapping[str, object]], DockerRunner],
             observer: Optional[PullObserver] = None,
             source_commit: Optional[str] = None) -> dict:
    """Internal injection seam.  The public CLI cannot supply any dependency."""
    _absolute(out, "--out")
    if os.path.lexists(out):
        raise _refuse("--out must be absent")
    refuse_ambient({})  # explicit seam: callers must preflight their real env
    require_phase_gates(phase, gates)
    docker_cli.reset_phase()
    authority, reference = docker_cli.begin_phase()
    require_base_pull_authority_binding(phase, gates, authority, reference)
    expected_reference = dict(reference)

    def revalidate() -> Mapping[str, object]:
        docker_cli.reset_phase()
        current, current_reference = docker_cli.begin_phase()
        if current_reference != expected_reference:
            raise PhaseFailure("identity_mismatch",
                               "Docker authority reference changed during phase")
        if current.get("daemon", {}).get("fingerprint_sha256") \
                != authority.get("daemon", {}).get("fingerprint_sha256"):
            raise PhaseFailure("identity_mismatch",
                               "Docker daemon fingerprint changed during phase")
        return current

    fingerprint = authority.get("daemon", {}).get("fingerprint_sha256")
    _full_sha256(fingerprint, "authority daemon fingerprint")
    root = os.path.dirname(os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__)))))
    commit = source_commit or _source_commit(root)
    started_utc = _window_utc()
    started_mono = time.monotonic()
    output = PrivateOutput(out)
    with producer_lock(fingerprint):
        output.create()
        runner = runner_factory(expected_reference)
        session = CommandSession(runner, output, revalidate)
        before: dict = {}
        after: dict = {}
        result: dict = {}
        status = "complete"
        failure: Optional[Exception] = None
        leftovers: list[dict] = []
        success_cleanup: dict = {}
        try:
            before = inspected_inventory(session)
            if phase == "base-pull":
                result, after, success_cleanup = _base_phase(
                    session, gates, authority, observer or _production_observer(),
                    before, revalidate, output)
            elif phase == "discovery":
                result, after, success_cleanup = _discovery_phase(
                    session, gates, before, output, root, commit)
            else:
                result, after, success_cleanup = _canonical_phase(
                    session, gates, before, output, root, commit)
            # This is the one terminal authority check.  Only after it
            # succeeds can cleanup evidence describe a complete phase.
            revalidate()
        except Exception as exc:
            failure = exc
            if isinstance(exc, PhaseFailure):
                status = exc.status
            elif isinstance(exc, EPUBCheckImageRefused):
                status = ("identity_mismatch" if session.effect_attempted
                          else "refused_before_effect")
            else:
                status = "cleanup_unconfirmed"
            authority_ok = True
            try:
                revalidate()
            except Exception:
                authority_ok = False
                status = "cleanup_unconfirmed"
            if authority_ok:
                try:
                    after = inspected_inventory(session)
                except Exception:
                    after = {}
                    status = "cleanup_unconfirmed"
            if before and after:
                leftovers = _inventory_leftovers(before, after)
                if leftovers:
                    status = "cleanup_unconfirmed"
            elif session.effect_attempted:
                status = "cleanup_unconfirmed"
            result = {"error": str(exc),
                      "effect_attempted": session.effect_attempted,
                      "authority_revalidated": authority_ok}
        cleanup = (success_cleanup if failure is None else {
            "status": status, "leftovers": leftovers,
            "error": str(failure)})
        output.write_raw("cleanup.json", json.dumps(
            cleanup, sort_keys=True, separators=(",", ":")).encode() + b"\n")
        transcript = {
            "schema": TRANSCRIPT_SCHEMA, "project": PROJECT,
            "phase": phase, "status": status,
            "source": {"commit": commit, "proposal_commit": PROPOSAL_COMMIT,
                       "proposal_sha256": PROPOSAL_SHA256},
            "window": {"started_utc": started_utc, "ended_utc": _window_utc(),
                       "monotonic_seconds": time.monotonic() - started_mono},
            "authority": {"reference": expected_reference,
                          "daemon_fingerprint": fingerprint},
            "gates": _gate_record(phase, gates),
            "commands": session.commands,
            "inventories": {"before": before, "after": after},
            "leftovers": leftovers, "artifacts": [], "cleanup": cleanup,
            "result": result,
        }
        transcript = output.finalize(transcript)
        if failure is not None:
            raise failure
        return transcript


def produce_epubcheck_image(*, phase: str, out: str) -> dict:
    """Production entry: no backend, host, digest, manifest, or observer input."""
    _absolute(out, "--out")
    if os.path.lexists(out):
        raise _refuse("--out must be absent")
    refuse_ambient(os.environ)
    configured = docker_cli.configured_authority_path()
    if configured is None or not os.path.isabs(configured):
        raise _refuse("image production requires one absolute --docker-authority")
    gates = require_phase_gates(phase)
    return _produce(
        phase=phase, out=out, gates=gates,
        runner_factory=lambda reference: LiveDockerRunner(reference),
        observer=None)
