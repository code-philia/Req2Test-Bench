class MavenCoordinate:
    group_id: str
    artifact_id: str
    version: str
    extension: str
    classifier: Optional[str] = None

    @property
    def gav(self) -> str:
        return ":".join((self.group_id, self.artifact_id, self.version))

    @property
    def path(self) -> str:
        suffix = "" if self.classifier is None else "-" + self.classifier
        filename = (f"{self.artifact_id}-{self.version}{suffix}."
                    f"{self.extension}")
        return "/".join((self.group_id.replace(".", "/"), self.artifact_id,
                         self.version, filename))


def coordinate_from_path(path: str) -> MavenCoordinate:
    """Parse an exact Maven JAR/POM payload path; reject metadata and aliases."""
    path = _relative_m2_path(path)
    parts = path.split("/")
    if len(parts) < 4:
        raise _refuse(f"Maven payload path is too short: {path}")
    artifact, version, filename = parts[-3:]
    group = ".".join(parts[:-3])
    if any(_TOKEN.fullmatch(token) is None for token in (group, artifact, version)):
        raise _refuse(f"Maven payload path has an invalid coordinate: {path}")
    if "SNAPSHOT" in version.upper() or filename.startswith("maven-metadata"):
        raise _refuse(f"snapshot/metadata path is forbidden: {path}")
    match = re.fullmatch(re.escape(artifact) + "-" + re.escape(version)
                         + r"(?:-([A-Za-z0-9_.+\-]+))?\.(jar|pom)", filename)
    if match is None:
        raise _refuse(f"Maven payload filename is not coordinate-canonical: {path}")
    classifier, extension = match.groups()
    if classifier is not None and classifier.lower() in REFUSED_CLASSIFIERS:
        raise _refuse(f"refused Maven classifier {classifier!r}: {path}")
    coordinate = MavenCoordinate(group, artifact, version, extension, classifier)
    if coordinate.path != path:
        raise _refuse(f"Maven payload path is not canonical: {path}")
    return coordinate


@dataclass(frozen=True)
class ManifestRow:
    path: str
    coordinate: MavenCoordinate
    size: int
    sha1: str
    sha256: str


_MANIFEST_HEADER = (
    "path", "group_id", "artifact_id", "version", "extension",
    "classifier", "size", "sha1", "sha256")


def parse_canonical_manifest(raw: bytes | str) -> tuple[ManifestRow, ...]:
    """Parse the completed payload-only, size/SHA-1/SHA-256 manifest."""
    if isinstance(raw, bytes):
        try:
            text = raw.decode("utf-8")
        except UnicodeDecodeError as exc:
            raise _refuse("canonical manifest is not UTF-8") from exc
    elif isinstance(raw, str):
        text = raw
    else:
        raise _refuse("canonical manifest is not bytes or text")
    if not text.endswith("\n") or "\r" in text or "\x00" in text:
        raise _refuse("canonical manifest must be LF-only and end in LF")
    lines = text[:-1].split("\n")
    if len(lines) < 3 or lines[0] != CANONICAL_MANIFEST_SCHEMA \
            or tuple(lines[1].split("\t")) != _MANIFEST_HEADER:
        raise _refuse("canonical manifest schema/header differs")
    rows = []
    paths = set()
    total = 0
    for number, line in enumerate(lines[2:], 3):
        fields = line.split("\t")
        if len(fields) != len(_MANIFEST_HEADER):
            raise _refuse(f"canonical manifest row {number} has wrong field count")
        path, group, artifact, version, extension, classifier_text, size_text, sha1, sha256 = fields
        coordinate = coordinate_from_path(path)
        classifier = None if classifier_text == "-" else classifier_text
        if (coordinate.group_id, coordinate.artifact_id, coordinate.version,
                coordinate.extension, coordinate.classifier) != (
                    group, artifact, version, extension, classifier):
            raise _refuse(f"canonical manifest row {number} coordinate/path disagree")
        try:
            size = int(size_text)
        except ValueError as exc:
            raise _refuse(f"canonical manifest row {number} size is not decimal") from exc
        if str(size) != size_text or size < 0:
            raise _refuse(f"canonical manifest row {number} size is noncanonical")
        if _SHA1.fullmatch(sha1) is None or _SHA256.fullmatch(sha256) is None:
            raise _refuse(f"canonical manifest row {number} checksum is malformed")
        if path in paths:
            raise _refuse(f"canonical manifest repeats path {path}")
        paths.add(path)
        total += size
        if len(paths) > DISCOVERY_MAX_FILES or total > DISCOVERY_MAX_BYTES:
            raise _refuse("canonical manifest exceeds the discovery ceiling")
        rows.append(ManifestRow(path, coordinate, size, sha1, sha256))
    if [row.path for row in rows] != sorted(row.path for row in rows):
        raise _refuse("canonical manifest paths are not bytewise sorted")
    return tuple(rows)


@dataclass
class ResponseBudget:
    """Count accepted Central response files/bytes with inclusive limits."""
    files: int = 0
    bytes: int = 0
    paths: set[str] = field(default_factory=set)

    def admit(self, path: str, size: int) -> None:
        _relative_m2_path(path, "Central response path")
        if not isinstance(size, int) or isinstance(size, bool) or size < 0:
            raise _refuse("Central response size is not a nonnegative integer")
        if path in self.paths:
            return
        if self.files == DISCOVERY_MAX_FILES:
            raise _refuse("Central response would be file 4,097")
        if self.bytes + size > DISCOVERY_MAX_BYTES:
            raise _refuse("Central response would exceed 2 GiB")
        self.paths.add(path)
        self.files += 1
        self.bytes += size


def validate_discovery_maven_argv(argv: Sequence[str]) -> tuple[str, ...]:
    value = tuple(argv)
    if value != DISCOVERY_MAVEN_ARGV:
        raise _refuse("discovery Maven argv differs from the exact one-command shape")
    forbidden = {"-o", "--offline", "-q", "--quiet", "-ntp",
                 "--no-transfer-progress"}
    if forbidden.intersection(value) or value.count("test") != 1:
        raise _refuse("discovery Maven argv suppresses resolution or adds a goal")
    return value


def base_reference(gates: SourceGates) -> str:
    if gates.base_digest is None or _DIGEST.fullmatch(gates.base_digest) is None:
        raise _refuse("approved base digest is absent/malformed")
    return BASE_NAME + "@" + gates.base_digest


def base_repo_digest_references(gates: SourceGates) -> tuple[str, str]:
    """Return Docker's canonical and familiar tag-free RepoDigest spellings.

    A digest-qualified pull reference contains the selected tag before ``@``;
    an image inspect RepoDigest does not.  Docker may expose the fully
    normalized repository name or its official-image familiar form, so both
    exact spellings are admitted while every other repository remains closed.
    """
    if gates.base_digest is None or _DIGEST.fullmatch(gates.base_digest) is None:
        raise _refuse("approved base digest is absent/malformed")
    return (BASE_REPOSITORY + "@" + gates.base_digest,
            BASE_FAMILIAR_REPOSITORY + "@" + gates.base_digest)


def discovery_definition(gates: SourceGates) -> bytes:
    """Return the sole future D-6 Dockerfile and bind its approved bytes."""
    argv = validate_discovery_maven_argv(gates.discovery_maven_argv or ())
    definition = (
        f"FROM {base_reference(gates)}\n"
        "COPY .r2t/settings.xml /root/.m2/settings.xml\n"
        "COPY pom.xml /r2t-discovery/pom.xml\n"
        "COPY src/ /r2t-discovery/src/\n"
        "WORKDIR /r2t-discovery\n"
        "RUN " + json.dumps(list(argv), separators=(",", ":")) + "\n"
    ).encode("utf-8")
    approved = gates.discovery_definition_sha256
    if approved is None or hashlib.sha256(definition).hexdigest() != approved:
        raise _refuse("generated discovery definition differs from approved bytes")
    return definition


def validate_discovery_definition(raw: bytes, gates: SourceGates) -> str:
    """Require the committed discovery definition to equal its approved shape."""
    if not isinstance(raw, bytes):
        raise _refuse("discovery definition is not bytes")
    expected = discovery_definition(gates)
    if raw != expected:
        raise _refuse("committed discovery definition differs from approved bytes")
    return hashlib.sha256(raw).hexdigest()


def canonical_definition_for_reference(reference: str) -> bytes:
    """The one payload-only canonical Dockerfile shape.

    The source-only definition passes the deliberately invalid
    ``...@DIGEST-PENDING`` reference.  A live canonical phase passes the
    separately approved digest-pinned reference.  Keeping the remaining
    bytes here prevents the inert source check and live producer from growing
    two definitions of the same image.
    """
    if not isinstance(reference, str) or not reference \
            or any(char.isspace() for char in reference):
        raise _refuse("canonical base reference is malformed")
    return (
        f"FROM {reference} AS payloads\n"
        "COPY approved-m2/ /opt/m2/\n\n"
        f"FROM {reference}\n"
        "COPY --from=payloads /opt/m2/ /opt/m2/\n"
        "COPY offline-settings.xml /root/.m2/settings.xml\n"
        "ENV LANG=C.UTF-8 LC_ALL=C.UTF-8 TZ=UTC\n"
        "WORKDIR /work\n"
        "ENTRYPOINT []\n"
        "CMD [\"tail\",\"-f\",\"/dev/null\"]\n").encode("utf-8")


def validate_canonical_definition(raw: bytes, gates: SourceGates) -> str:
    """Validate the source-bound two-FROM, payload-only final definition."""
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError as exc:
        raise _refuse("canonical Dockerfile is not UTF-8") from exc
    approved = gates.canonical_definition_sha256
    if approved is None or hashlib.sha256(raw).hexdigest() != approved:
        raise _refuse("canonical Dockerfile differs from approved bytes")
    ref = base_reference(gates)
    expected = canonical_definition_for_reference(ref).decode("utf-8")
    if text != expected:
        raise _refuse("canonical Dockerfile is not the exact payload-only shape")
    if text.count("FROM " + ref) != 2:
        raise _refuse("canonical Dockerfile does not have two equal literal FROMs")
    return text


def validate_context_paths(paths: Iterable[str], *, phase: str) -> tuple[str, ...]:
    actual = tuple(sorted(paths))
    if phase == "discovery":
        if not actual or actual[0] != ".r2t/settings.xml" \
                or "Dockerfile.discovery" not in actual \
                or "pom.xml" not in actual \
                or not any(path.startswith("src/") for path in actual):
            raise _refuse("discovery context omits a required committed input")
        allowed = lambda path: path in {"Dockerfile.discovery", "pom.xml",
                                        ".r2t/settings.xml"} \
            or path.startswith("src/")
    elif phase == "canonical":
        allowed = lambda path: path in {"Dockerfile", "offline-settings.xml"} \
            or path.startswith("approved-m2/")
        if "Dockerfile" not in actual or "offline-settings.xml" not in actual \
                or not any(path.startswith("approved-m2/") for path in actual):
            raise _refuse("canonical context omits definition/settings/payloads")
    else:
        raise _refuse("context phase is unknown")
    bad = [path for path in actual if not allowed(path) or path.startswith("/")
           or posixpath.normpath(path) != path or "//" in path]
    if bad:
        raise _refuse(f"{phase} context contains extra/unsafe paths: {bad}")
    return actual


_DOCKER_OBJECT_ID = re.compile(r"(?:sha256:)?[0-9a-f]{64}\Z")
_ATTEMPT_ID = re.compile(r"[0-9a-f]{16}\Z")
_ATTEMPT_NAME = re.compile(
    r"r2t-ei-(?:canonical-(?:egress|helper|capture)|"
    r"source-free|compile|helper|capture|egress|private|java|maven|jacoco)-"
    r"([0-9a-f]{16})\Z")
_VOLUME_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,254}\Z")
_ATTEMPT_ROOT_NAME = re.compile(r"r2t-epubcheck-image-[A-Za-z0-9_.-]+\Z")


def _is_attempt_root(value: str) -> bool:
    return os.path.dirname(value) == ATTEMPT_PARENT \
        and _ATTEMPT_ROOT_NAME.fullmatch(os.path.basename(value)) is not None


def _docker_ref(value: str, *, family: str) -> None:
    """Validate only references which an emitted operation can address."""
    if _DOCKER_OBJECT_ID.fullmatch(value):
        return
    if family == "image" and (value == CONVENIENCE_TAG or re.fullmatch(
            re.escape(BASE_NAME) + r"@sha256:[0-9a-f]{64}", value)):
        return
    if family in {"container", "network"} and _ATTEMPT_NAME.fullmatch(value):
        return
    if family == "volume" and _VOLUME_NAME.fullmatch(value):
        return
    raise _refuse(f"Docker {family} reference is outside producer ownership")


def _bind_source(value: str, *, target: str, readonly: bool) -> str:
    suffix = ",readonly" if readonly else ""
    prefix = "type=bind,source="
    marker = ",target=" + target + suffix
    if not value.startswith(prefix) or not value.endswith(marker):
        raise _refuse(f"Docker bind is not the exact {target} mount")
    source = value[len(prefix):-len(marker)]
    if not source or "," in source:
        raise _refuse("Docker bind source is empty/ambiguous")
    return _absolute(source, "Docker bind source")


def _create_prefix(value: tuple[str, ...]) -> tuple[str, str, str, tuple[str, ...]]:
    if len(value) < 13 or value[:3] != ("container", "create", "--name"):
        raise _refuse("container create omits its exact named prefix")
    name = value[3]
    match = _ATTEMPT_NAME.fullmatch(name)
    if match is None:
        raise _refuse("container create name is not attempt-scoped")
    expected = (
        "--label", "r2t.workload=epubcheck-image",
        "--label", value[7], "--label", value[9], "--network", value[11])
    if value[4:12] != expected \
            or value[7] not in {"r2t.phase=discovery", "r2t.phase=canonical"} \
            or value[9] != "r2t.attempt=" + match.group(1):
        raise _refuse("container create labels/network prefix differs")
    return name, value[7].removeprefix("r2t.phase="), value[11], value[12:]


def _validate_container_create(value: tuple[str, ...]) -> None:
    name, phase, network, rest = _create_prefix(value)
    match = _ATTEMPT_NAME.fullmatch(name)
    assert match is not None
    attempt = match.group(1)
    # The compile-only container is the sole javac operation.
    compiler_head = (
        "--read-only", "--tmpfs", "/tmp:rw,noexec,nosuid,nodev,size=64m",
        "--entrypoint", "/opt/java/openjdk/bin/javac", "--mount")
    if rest[:len(compiler_head)] == compiler_head:
        if network != "none" or not name.startswith("r2t-ei-compile-") \
                or len(rest) != 19 or rest[7] != "--mount":
            raise _refuse("helper compiler container shape differs")
        source = _bind_source(
            rest[6], target="/r2t-src/R2TMavenGateway.java", readonly=True)
        classes = _bind_source(rest[8], target="/r2t-classes", readonly=False)
        root = os.path.dirname(os.path.dirname(source))
        if not _is_attempt_root(root) or source != os.path.join(
                root, "helper_source", "R2TMavenGateway.java") \
                or classes != os.path.join(root, "classes") \
                or _IMAGE_ID.fullmatch(rest[9]) is None \
                or rest[10:] != ("-encoding", "UTF-8", "-source", "8",
                                  "-target", "8", "-d", "/r2t-classes",
                                  "/r2t-src/R2TMavenGateway.java"):
            raise _refuse("helper compiler inputs/command differ")
        return

    helper_head = (
        "--read-only", "--tmpfs", "/tmp:rw,noexec,nosuid,nodev,size=64m",
        "--entrypoint", "/opt/java/openjdk/bin/java", "--mount")
    if rest[:len(helper_head)] == helper_head:
        if len(rest) != 16 or rest[7] != "--mount" or rest[9] != "--mount":
            raise _refuse("Maven gateway container shape differs")
        classes = _bind_source(rest[6], target="/r2t-classes", readonly=True)
        config = _bind_source(rest[8], target="/r2t/config", readonly=True)
        root = os.path.dirname(classes)
        if not _is_attempt_root(root) or config != os.path.join(root, "config"):
            raise _refuse("Maven gateway mounts do not share one attempt")
        if phase == "discovery":
            expected_name = "r2t-ei-helper-" + attempt
            third_target, mode = "/r2t/cache", "serve-discovery"
        else:
            expected_name = "r2t-ei-canonical-helper-" + attempt
            third_target, mode = "/r2t/output", "prefetch-exact"
        third = _bind_source(rest[10], target=third_target, readonly=False)
        expected_source = os.path.join(
            root, "cache" if phase == "discovery" else "prefetch")
        if name != expected_name \
                or _DOCKER_OBJECT_ID.fullmatch(network) is None \
                or classes != os.path.join(root, "classes") \
                or third != expected_source or _IMAGE_ID.fullmatch(rest[11]) is None \
                or rest[12:] != ("-cp", "/r2t-classes", "R2TMavenGateway", mode):
            raise _refuse("Maven gateway network/image/command differs")
        return

    # Repository capture is the only container allowed to inherit image CMD.
    if rest and rest[0].startswith("sha256:"):
        expected_name = ("r2t-ei-capture-" if phase == "discovery" else
                         "r2t-ei-canonical-capture-") + attempt
        if name != expected_name or network != "none" \
                or len(rest) != 4 or _IMAGE_ID.fullmatch(rest[0]) is None \
                or rest[1:] != ("tail", "-f", "/dev/null"):
            raise _refuse("repository capture container shape differs")
        return

    # Canonical qualification probes have one of five fixed commands.
    probe_head = (
        "--read-only", "--tmpfs", "/tmp:rw,noexec,nosuid,nodev,size=256m",
        "--entrypoint")
    if rest[:len(probe_head)] != probe_head or phase != "canonical" \
            or network != "none":
        raise _refuse("container create is not one emitted producer shape")
    entrypoint = rest[4]
    tail = rest[5:]
    mounts: tuple[str, ...] = ()
    if tail[:1] == ("--mount",):
        if len(tail) < 3:
            raise _refuse("qualification mount is incomplete")
        mounts = (tail[1],)
        tail = tail[2:]
    if not tail or _IMAGE_ID.fullmatch(tail[0]) is None:
        raise _refuse("qualification probe image ID differs")
    command = tail[1:]
    source_free = (
        "-c", "set -eu; test ! -e /r2t-discovery; test ! -e /r2t-src; "
        "test ! -e /src; test ! -e /pom.xml; "
        "test -z \"$(find /work -mindepth 1 -print -quit)\"")
    variants = {
        "source-free": ("/bin/sh", source_free, False),
        "java": ("/opt/java/openjdk/bin/java", ("-version",), False),
        "maven": ("/usr/share/maven/bin/mvn", ("--version",), False),
        "compile": ("/usr/share/maven/bin/mvn",
                    ("-o", "-B", "-Dmaven.repo.local=/opt/m2", "test-compile"), True),
        "jacoco": ("/usr/share/maven/bin/mvn",
                   ("-o", "-B", "-Dmaven.repo.local=/opt/m2",
                    "org.jacoco:jacoco-maven-plugin:0.8.11:help"), True),
    }
    kind = name[len("r2t-ei-"):-(len(attempt) + 1)]
    expected = variants.get(kind)
    if expected is None or (entrypoint, command, bool(mounts)) != expected:
        raise _refuse("qualification probe command differs")
    if mounts:
        source = _bind_source(mounts[0], target="/work", readonly=False)
        root = os.path.dirname(source)
        if not _is_attempt_root(root) \
                or source != os.path.join(root, "workspace-" + kind):
            raise _refuse("qualification workspace mount differs")


def _validate_build_argv(value: tuple[str, ...]) -> None:
    if len(value) != 12 or value[1:6] != (
            "--no-cache", "--pull=false", "--rm=true", "--force-rm", "--network") \
            or value[7] != "--iidfile" or value[9] != "--file":
        raise _refuse("Docker build argv differs from the exact legacy shape")
    network, iidfile, definition, context = value[6], value[8], value[10], value[11]
    root = os.path.dirname(context)
    if not _is_attempt_root(root) or context != os.path.join(root, "context"):
        raise _refuse("Docker build context is outside one private attempt")
    if network == "none":
        iid_name, definition_name = "canonical.iid", "Dockerfile"
    elif _DOCKER_OBJECT_ID.fullmatch(network):
        iid_name, definition_name = "discovery.iid", "Dockerfile.discovery"
    else:
        raise _refuse("Docker build network is neither an immutable ID nor none")
    if iidfile != os.path.join(root, "volatile", iid_name) \
            or definition != os.path.join(root, "context", definition_name):
        raise _refuse("Docker build iidfile/definition differs")


def validate_docker_inner_argv(argv: Sequence[str]) -> tuple[str, ...]:
    """Admit only the exact Docker operation shapes emitted by this producer."""
    try:
        value = tuple(argv)
    except TypeError as exc:
        raise _refuse("Docker inner argv is not a sequence") from exc
    if not value or any(not isinstance(token, str) or not token or "\x00" in token
                        for token in value):
        raise _refuse("Docker inner argv is empty/malformed")

    if value[0] == "build":
        _validate_build_argv(value)
        return value
    if len(value) < 2:
        raise _refuse("Docker command omits its subcommand")
    family, operation = value[:2]

    if family == "image":
        if value == ("image", "ls", "--all", "--no-trunc", "--quiet"):
            return value
        if operation == "inspect" and len(value) in {3, 5}:
            _docker_ref(value[2], family="image")
            if len(value) == 5 and value[3:] != ("--format", "{{json .}}"):
                raise _refuse("image inspect format differs")
            return value
        if operation == "pull" and len(value) == 5 \
                and value[2:4] == ("--platform", "linux/amd64") \
                and re.fullmatch(re.escape(BASE_NAME) +
                                 r"@sha256:[0-9a-f]{64}", value[4]):
            return value
        if operation == "tag" and len(value) == 4 \
                and _IMAGE_ID.fullmatch(value[2]) and value[3] == CONVENIENCE_TAG:
            return value
        if operation == "rm" and len(value) == 3 and _IMAGE_ID.fullmatch(value[2]):
            return value
        raise _refuse("image operation is not one emitted producer shape")

    if family == "container":
        if value == ("container", "ls", "--all", "--no-trunc", "--quiet"):
            return value
        if operation == "inspect" and len(value) in {3, 5}:
            _docker_ref(value[2], family="container")
            if len(value) == 5 and value[3:] != ("--format", "{{json .}}"):
                raise _refuse("container inspect format differs")
            return value
        if operation == "create":
            _validate_container_create(value)
            return value
        if operation == "start" and (len(value) == 3 or (
                len(value) == 4 and value[2] == "--attach")):
            if _DOCKER_OBJECT_ID.fullmatch(value[-1]) is None:
                raise _refuse("container start does not name one immutable ID")
            return value
        if operation in {"stop", "rm", "logs"} and len(value) == 3:
            if _DOCKER_OBJECT_ID.fullmatch(value[2]) is None:
                raise _refuse(f"container {operation} does not name one immutable ID")
            return value
        if operation == "cp" and len(value) == 4 and value[3] == "-" \
                and value[2].endswith(":/opt/m2"):
            if _DOCKER_OBJECT_ID.fullmatch(
                    value[2][:-len(":/opt/m2")]) is None:
                raise _refuse("container cp does not name one immutable ID")
            return value
        raise _refuse("container operation is not one emitted producer shape")

    if family == "network":
        if value == ("network", "ls", "--no-trunc", "--quiet"):
            return value
        if operation == "inspect" and len(value) in {3, 5}:
            _docker_ref(value[2], family="network")
            if len(value) == 5 and value[3:] != ("--format", "{{json .}}"):
                raise _refuse("network inspect format differs")
            return value
        if operation == "create":
            internal = value[-2:-1] == ("--internal",)
            name_index = -1
            labels_end = len(value) - (2 if internal else 1)
            if value[:4] != ("network", "create", "--driver", "bridge") \
                    or labels_end != 10 or value[4:10:2] != (
                        "--label", "--label", "--label"):
                raise _refuse("network create options differ")
            name = value[name_index]
            match = _ATTEMPT_NAME.fullmatch(name)
            phase_value = value[7]
            if match is None or value[5] != "r2t.workload=epubcheck-image" \
                    or phase_value not in {"r2t.phase=discovery", "r2t.phase=canonical"} \
                    or value[9] != "r2t.attempt=" + match.group(1):
                raise _refuse("network create labels/name differ")
            if phase_value == "r2t.phase=canonical":
                valid = name == "r2t-ei-canonical-egress-" + match.group(1) \
                    and not internal
            else:
                valid = name == ("r2t-ei-private-" if internal else
                                 "r2t-ei-egress-") + match.group(1)
            if not valid:
                raise _refuse("network create phase/internal role differs")
            return value
        if operation == "connect" and len(value) == 4 \
                and _DOCKER_OBJECT_ID.fullmatch(value[2]) is not None:
            if _DOCKER_OBJECT_ID.fullmatch(value[3]) is None:
                raise _refuse(
                    "network connect does not name immutable network/container IDs")
            return value
        if operation == "rm" and len(value) == 3:
            if _DOCKER_OBJECT_ID.fullmatch(value[2]) is None:
                raise _refuse("network rm does not name one immutable ID")
            return value
        raise _refuse("network operation is not one emitted producer shape")

    if family == "volume":
        if value == ("volume", "ls", "--quiet"):
            return value
        if operation == "inspect" and len(value) == 5 \
                and value[3:] == ("--format", "{{json .}}"):
            _docker_ref(value[2], family="volume")
            return value
        raise _refuse("volume operation is not one emitted producer shape")

    raise _refuse("Docker command family is outside the closed vocabulary")


