def _refuse(message: str) -> EPUBCheckImageRefused:
    return EPUBCheckImageRefused("REFUSED: " + message)


def _full_sha256(value: object, label: str) -> str:
    if not isinstance(value, str) or _SHA256.fullmatch(value) is None:
        raise _refuse(f"{label} is not one lower-case full SHA-256")
    return value


def _image_id(value: object, label: str) -> str:
    if not isinstance(value, str) or _IMAGE_ID.fullmatch(value) is None:
        raise _refuse(f"{label} is not one immutable sha256 image ID")
    return value


def _absolute(value: object, label: str) -> str:
    if not isinstance(value, str) or not value or "\x00" in value \
            or not os.path.isabs(value) or os.path.normpath(value) != value:
        raise _refuse(f"{label} must be one normalized absolute path")
    return value


def _printable_identity(value: object) -> bool:
    return isinstance(value, str) and 0 < len(value) <= 512 and all(
        0x21 <= ord(character) <= 0x7e for character in value)


def _normalized_absolute(value: object) -> bool:
    return isinstance(value, str) and bool(value) and "\x00" not in value \
        and os.path.isabs(value) and os.path.normpath(value) == value


def _relative_m2_path(value: object, label: str = "Maven path") -> str:
    if not isinstance(value, str) or not value or value.startswith("/") \
            or "\x00" in value or "\r" in value or "\n" in value \
            or _M2_PATH.fullmatch(value) is None:
        raise _refuse(f"{label} is not one portable relative Maven path")
    if posixpath.normpath(value) != value or value == "." \
            or value.startswith("../") or "//" in value:
        raise _refuse(f"{label} is not normalized beneath the Maven root")
    return value


def _exact_object(value: object, fields: Iterable[str], label: str) -> dict:
    if not isinstance(value, dict):
        raise _refuse(f"{label} is not an object")
    expected = set(fields)
    actual = set(value)
    if actual != expected:
        raise _refuse(
            f"{label} fields differ; missing={sorted(expected - actual)}, "
            f"unknown={sorted(actual - expected)}")
    return value


def refuse_ambient(environ: Mapping[str, str]) -> None:
    """Reject selectors/injection knobs without reading their values."""
    present = sorted(key for key in _AMBIENT_KEYS if key in environ)
    if present:
        raise _refuse(
            "ambient Docker/proxy/JVM/Maven selectors are present: "
            + ", ".join(present))


