def phase_gate_findings(phase: str, gates: SourceGates) -> list[str]:
    """Return every source gate that keeps one phase closed."""
    if phase not in PHASES:
        return [f"phase: expected one of {list(PHASES)}, got {phase!r}"]
    found = []
    if gates.implemented is not True:
        found.append("implementation: producer source is not implemented")
    if not _printable_identity(gates.partial_path_a):
        found.append("partial_path_a: EPUBCheck-only Path A identity is absent/malformed")
    if not isinstance(gates.base_digest, str) \
            or _DIGEST.fullmatch(gates.base_digest) is None:
        found.append("base_digest: exact Maven base digest is absent/malformed")
    if not _printable_identity(gates.live_fixture_qualification):
        found.append("live_fixture: selected-adapter fixture identity is absent/malformed")
    if phase == "base-pull":
        if gates.pull_observer_implemented is not True:
            found.append("pull_observer_implementation: lossless R-1 observer is not implemented")
        if not _printable_identity(gates.pull_observer):
            found.append("pull_observer: lossless R-1 observer identity is absent/malformed")
        if not _printable_identity(gates.base_pull_execution):
            found.append("base_pull_execution: exact execution identity is absent/malformed")
        return found
    amendment_valid = _printable_identity(gates.full_id_addressing_amendment)
    resolution_valid = _printable_identity(
        gates.docker_name_id_resolution_decision)
    if not amendment_valid:
        found.append(
            "full_id_addressing_amendment: exact amendment approval identity "
            "is absent/malformed")
    if not resolution_valid:
        found.append(
            "docker_name_id_resolution_decision: exact Docker name-or-ID "
            "resolution decision identity is absent/malformed")
    if amendment_valid and resolution_valid \
            and gates.full_id_addressing_amendment \
            == gates.docker_name_id_resolution_decision:
        found.append(
            "docker_name_id_resolution_decision: amendment approval cannot "
            "substitute for the independent resolution decision")
    if not isinstance(gates.base_pull_transcript_sha256, str) \
            or _SHA256.fullmatch(gates.base_pull_transcript_sha256) is None:
        found.append("base_pull_transcript: approved transcript SHA-256 is absent/malformed")
    if not isinstance(gates.base_config_id, str) \
            or _IMAGE_ID.fullmatch(gates.base_config_id) is None:
        found.append("base_config: approved base config ID is absent/malformed")
    if not isinstance(gates.redirect_host, str) \
            or _DNS_HOST.fullmatch(gates.redirect_host) is None \
            or gates.redirect_host in {CENTRAL_HOST, "repo1.maven.org",
                                       "auth.docker.io", "registry-1.docker.io"}:
        found.append(
            "redirect_host: R-1 is absent or not one distinct normalized host")
    if not _normalized_absolute(gates.base_pull_authority_path):
        found.append("base_pull_authority_path: approved authority path is absent/malformed")
    for label, value in (
            ("base_pull_authority_file", gates.base_pull_authority_file_sha256),
            ("base_pull_authority_digest", gates.base_pull_authority_digest),
            ("base_pull_daemon", gates.base_pull_daemon_fingerprint)):
        if not isinstance(value, str) or _SHA256.fullmatch(value) is None:
            found.append(f"{label}: approved authority projection is absent/malformed")
    if gates.helper_topology_observer_implemented is not True:
        found.append(
            "helper_topology_implementation: lossless shared-daemon topology "
            "observation is not implemented")
    if not _printable_identity(gates.helper_topology_observer):
        found.append(
            "helper_topology_observer: lossless topology observation identity "
            "is absent/malformed")
    if phase == "discovery":
        if not _printable_identity(gates.d6_modification):
            found.append("d6_modification: gateway modification identity is absent/malformed")
        if not _printable_identity(gates.d6_execution):
            found.append("d6_execution: discovery execution identity is absent/malformed")
        if not isinstance(gates.discovery_definition_sha256, str) \
                or _SHA256.fullmatch(gates.discovery_definition_sha256) is None:
            found.append("discovery_definition: exact definition SHA-256 is absent/malformed")
        if gates.discovery_maven_argv != DISCOVERY_MAVEN_ARGV:
            found.append("discovery_maven_argv: exact one-command argv is not approved")
        return found
    if not isinstance(gates.completed_census_sha256, str) \
            or _SHA256.fullmatch(gates.completed_census_sha256) is None:
        found.append("completed_census: approved census SHA-256 is absent/malformed")
    if not isinstance(gates.canonical_manifest_sha256, str) \
            or _SHA256.fullmatch(gates.canonical_manifest_sha256) is None:
        found.append("canonical_manifest: approved manifest SHA-256 is absent/malformed")
    if not _printable_identity(gates.canonical_prefetch_modification):
        found.append("canonical_prefetch: E1 modification identity is absent/malformed")
    if not isinstance(gates.canonical_definition_sha256, str) \
            or _SHA256.fullmatch(gates.canonical_definition_sha256) is None:
        found.append("canonical_definition: exact Dockerfile SHA-256 is absent/malformed")
    if not _printable_identity(gates.canonical_execution):
        found.append("canonical_execution: execution identity is absent/malformed")
    if not _printable_identity(gates.canonical_tag_publication_waiver):
        found.append(
            "tag_publication_race: non-atomic convenience-tag publication "
            "has no exact waiver/redesign identity")
    return found


def require_phase_gates(phase: str, gates: Optional[SourceGates] = None) -> SourceGates:
    selected = source_gates() if gates is None else gates
    findings = phase_gate_findings(phase, selected)
    if findings:
        raise _refuse("image phase authority is closed.\n  - "
                      + "\n  - ".join(findings))
    return selected


def require_base_pull_authority_binding(
        phase: str, gates: SourceGates, authority: Mapping[str, object],
        reference: Mapping[str, object]) -> None:
    """Keep retained-base consumers on the approved producer authority."""
    if phase == "base-pull":
        return
    daemon = authority.get("daemon")
    observed = {
        "path": reference.get("path"),
        "file_sha256": reference.get("file_sha256"),
        "digest": reference.get("digest"),
        "daemon_fingerprint": (
            daemon.get("fingerprint_sha256")
            if isinstance(daemon, Mapping) else None),
    }
    approved = {
        "path": gates.base_pull_authority_path,
        "file_sha256": gates.base_pull_authority_file_sha256,
        "digest": gates.base_pull_authority_digest,
        "daemon_fingerprint": gates.base_pull_daemon_fingerprint,
    }
    if observed != approved:
        raise _refuse(
            "current Docker authority does not equal the approved base-pull "
            "path/file/semantic/daemon projection")


@dataclass(frozen=True)
class StableBytes:
    data: bytes
    sha256: str
    size: int
    identity: tuple[int, int, int, int, int, int, int, int]


def stable_read(path: str, *, max_bytes: Optional[int] = None) -> StableBytes:
    """Read one regular file once, without following links, and bind identity."""
    _absolute(path, "stable-read path")
    flags = os.O_RDONLY | getattr(os, "O_CLOEXEC", 0) \
        | getattr(os, "O_NOFOLLOW", 0)
    try:
        fd = os.open(path, flags)
    except OSError as exc:
        raise _refuse(f"cannot open stable input {path!r}: {exc}") from exc
    try:
        before = os.fstat(fd)
        if not stat.S_ISREG(before.st_mode):
            raise _refuse(f"stable input is not regular: {path}")
        if max_bytes is not None and before.st_size > max_bytes:
            raise _refuse(f"stable input exceeds {max_bytes} bytes: {path}")
        chunks = []
        seen = 0
        digest = hashlib.sha256()
        while True:
            chunk = os.read(fd, 1024 * 1024)
            if not chunk:
                break
            seen += len(chunk)
            if max_bytes is not None and seen > max_bytes:
                raise _refuse(f"stable input grew beyond {max_bytes} bytes: {path}")
            digest.update(chunk)
            chunks.append(chunk)
        after = os.fstat(fd)
        fields = lambda s: (s.st_dev, s.st_ino, stat.S_IFMT(s.st_mode),
                            s.st_uid, s.st_gid, s.st_size,
                            s.st_mtime_ns, s.st_ctime_ns)
        if fields(before) != fields(after) or seen != before.st_size:
            raise _refuse(f"stable input changed while read: {path}")
        return StableBytes(b"".join(chunks), digest.hexdigest(), seen,
                           fields(after))
    finally:
        os.close(fd)


