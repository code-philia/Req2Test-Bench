def _wait_bounded_process(proc: subprocess.Popen, *, timeout: int,
                          overflow: threading.Event,
                          cancel: Optional[threading.Event]) -> bool:
    """Wait with prompt TERM/KILL escalation for timeout, cap, or cancellation."""
    deadline = time.monotonic() + timeout
    termination_started: Optional[float] = None
    timed_out = False
    while True:
        try:
            proc.wait(timeout=0.1)
            return timed_out
        except subprocess.TimeoutExpired:
            now = time.monotonic()
        should_cancel = cancel is not None and cancel.is_set()
        if now >= deadline:
            timed_out = True
        if overflow.is_set() or should_cancel or timed_out:
            if termination_started is None:
                termination_started = now
                with contextlib.suppress(ProcessLookupError):
                    os.killpg(proc.pid, signal.SIGTERM)
            elif now - termination_started >= 5.0:
                with contextlib.suppress(ProcessLookupError):
                    os.killpg(proc.pid, signal.SIGKILL)
                proc.wait()
                return timed_out


def _bounded_process(argv: Sequence[str], *, timeout: int,
                     environ: Mapping[str, str],
                     cancel: Optional[threading.Event] = None) -> CommandResult:
    """Capture both pipes losslessly up to the reviewed cap; never retry."""
    try:
        proc = subprocess.Popen(
            list(argv), stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
            stderr=subprocess.PIPE, env=dict(environ), cwd="/",
            start_new_session=True)
    except OSError as exc:
        raise _refuse(f"Docker client could not start: {exc}") from exc
    buffers = [bytearray(), bytearray()]
    overflow = threading.Event()

    def drain(index: int, stream) -> None:
        while True:
            chunk = stream.read(64 * 1024)
            if not chunk:
                return
            remaining = MAX_RAW_LOG_BYTES + 1 - len(buffers[index])
            if remaining > 0:
                buffers[index].extend(chunk[:remaining])
            if len(buffers[index]) > MAX_RAW_LOG_BYTES:
                overflow.set()
                with contextlib.suppress(ProcessLookupError):
                    os.killpg(proc.pid, signal.SIGTERM)

    threads = [threading.Thread(target=drain, args=(0, proc.stdout), daemon=True),
               threading.Thread(target=drain, args=(1, proc.stderr), daemon=True)]
    for thread in threads:
        thread.start()
    timed_out = _wait_bounded_process(
        proc, timeout=timeout, overflow=overflow, cancel=cancel)
    for thread in threads:
        thread.join(timeout=5)
    if any(thread.is_alive() for thread in threads):
        raise _refuse("Docker client pipe did not close after termination")
    return CommandResult(tuple(argv), proc.returncode,
                         bytes(buffers[0][:MAX_RAW_LOG_BYTES]),
                         bytes(buffers[1][:MAX_RAW_LOG_BYTES]),
                         timed_out=timed_out, overflowed=overflow.is_set())


def _stream_process(argv: Sequence[str], *, timeout: int,
                    environ: Mapping[str, str], target: str,
                    maximum: int) -> StreamResult:
    flags = os.O_WRONLY | os.O_CREAT | os.O_EXCL \
        | getattr(os, "O_CLOEXEC", 0) | getattr(os, "O_NOFOLLOW", 0)
    fd = os.open(target, flags, 0o600)
    try:
        proc = subprocess.Popen(
            list(argv), stdin=subprocess.DEVNULL, stdout=subprocess.PIPE,
            stderr=subprocess.PIPE, env=dict(environ), cwd="/",
            start_new_session=True)
    except OSError as exc:
        os.close(fd)
        raise _refuse(f"Docker streaming client could not start: {exc}") from exc
    stderr = bytearray()
    overflow = threading.Event()
    digest = hashlib.sha256()
    size = [0]

    def drain_stdout() -> None:
        while True:
            chunk = proc.stdout.read(1024 * 1024)
            if not chunk:
                return
            size[0] += len(chunk)
            if size[0] > maximum:
                overflow.set()
                with contextlib.suppress(ProcessLookupError):
                    os.killpg(proc.pid, signal.SIGTERM)
                return
            digest.update(chunk)
            view = memoryview(chunk)
            while view:
                written = os.write(fd, view)
                view = view[written:]

    def drain_stderr() -> None:
        while True:
            chunk = proc.stderr.read(64 * 1024)
            if not chunk:
                return
            remaining = MAX_RAW_LOG_BYTES + 1 - len(stderr)
            if remaining > 0:
                stderr.extend(chunk[:remaining])
            if len(stderr) > MAX_RAW_LOG_BYTES:
                overflow.set()
                with contextlib.suppress(ProcessLookupError):
                    os.killpg(proc.pid, signal.SIGTERM)

    threads = [threading.Thread(target=drain_stdout, daemon=True),
               threading.Thread(target=drain_stderr, daemon=True)]
    for thread in threads:
        thread.start()
    timed_out = _wait_bounded_process(
        proc, timeout=timeout, overflow=overflow, cancel=None)
    for thread in threads:
        thread.join(timeout=5)
    os.fsync(fd)
    os.close(fd)
    if any(thread.is_alive() for thread in threads):
        raise _refuse("Docker streaming pipe did not close")
    return StreamResult(tuple(argv), proc.returncode,
                        bytes(stderr[:MAX_RAW_LOG_BYTES]), size[0],
                        digest.hexdigest(), timed_out, overflow.is_set())


class LiveDockerRunner:
    """The sole production bridge from exact inner argv to the selected daemon."""

    def __init__(
            self, authority_reference: Mapping[str, object], *,
            argv_validator: Callable[[Sequence[str]], tuple[str, ...]] =
            validate_docker_inner_argv,
            mutation_predicate: Callable[[Sequence[str]], bool] =
            docker_is_mutation):
        self.reference = dict(authority_reference)
        self._argv_validator = argv_validator
        self._mutation_predicate = mutation_predicate

    def _revalidate(self) -> dict:
        docker_cli.reset_phase()
        document, reference = docker_cli.begin_phase()
        if reference != self.reference:
            raise _refuse("Docker authority changed during image phase")
        return document

    def revalidate_authority(self) -> dict:
        """Return the exact live authority projection used by small producers."""
        document = self._revalidate()
        daemon = document.get("daemon")
        fingerprint = (daemon.get("fingerprint_sha256")
                       if isinstance(daemon, dict) else None)
        if not isinstance(fingerprint, str) or _SHA256.fullmatch(
                fingerprint) is None:
            raise _refuse("Docker authority omits its daemon fingerprint")
        return {"reference": dict(self.reference),
                "daemon_fingerprint": fingerprint}

    def run(self, argv: Sequence[str], *, timeout: int,
            build: bool = False,
            cancel: Optional[threading.Event] = None) -> CommandResult:
        inner = self._argv_validator(argv)
        if self._mutation_predicate(inner):
            self._revalidate()
        env = clean_subprocess_environment(build=build)
        outer = docker_cli.docker_command(inner, environ=env)
        result = _bounded_process(
            outer, timeout=timeout, environ=env, cancel=cancel)
        if result.timed_out or result.overflowed:
            # Revalidation happens immediately after either exceptional
            # network/client window, before cleanup can mutate anything.
            self._revalidate()
        return CommandResult(inner, result.returncode, result.stdout,
                             result.stderr, result.timed_out,
                             result.overflowed)

    def stream_to(self, argv: Sequence[str], *, timeout: int, target: str,
                  maximum: int) -> StreamResult:
        inner = self._argv_validator(argv)
        if self._mutation_predicate(inner):
            self._revalidate()
        env = clean_subprocess_environment()
        outer = docker_cli.docker_command(inner, environ=env)
        result = _stream_process(outer, timeout=timeout, environ=env,
                                 target=target, maximum=maximum)
        if result.timed_out or result.overflowed:
            self._revalidate()
        return StreamResult(inner, result.returncode, result.stderr,
                            result.size, result.sha256, result.timed_out,
                            result.overflowed)

    def capture_files(self, image_id: str, path: str, *, timeout: int,
                      maximum_files: int = DISCOVERY_MAX_FILES,
                      maximum_bytes: int = DISCOVERY_MAX_BYTES,
                      scratch_root: Optional[str] = None) \
            -> dict[str, bytes]:
        """Safely stream one immutable image's /opt/m2 without extraction."""
        if _IMAGE_ID.fullmatch(image_id) is None or path != "/opt/m2" \
                or not isinstance(timeout, int) or timeout <= 0 \
                or not isinstance(maximum_files, int) or maximum_files <= 0 \
                or not isinstance(maximum_bytes, int) or maximum_bytes <= 0 \
                or not isinstance(scratch_root, str) \
                or not os.path.isabs(scratch_root) \
                or os.path.normpath(scratch_root) != scratch_root:
            raise _refuse("repository capture request is malformed")
        info = os.stat(scratch_root, follow_symlinks=False)
        if not stat.S_ISDIR(info.st_mode) or stat.S_ISLNK(info.st_mode) \
                or info.st_uid != os.getuid() \
                or stat.S_IMODE(info.st_mode) != 0o700:
            raise _refuse("repository capture scratch is not owned/private")
        argv = (
            "run", "--rm", "--network", "none", "--pull=never",
            "--entrypoint", "/bin/tar", image_id,
            "-C", "/opt", "-cf", "-", "m2")
        with tempfile.TemporaryDirectory(
                prefix="r2t-m2-capture-", dir=scratch_root) as root:
            target = os.path.join(root, "repository.tar")
            overhead = max(64 * 1024 * 1024, maximum_files * 2048)
            result = self.stream_to(
                argv, timeout=timeout, target=target,
                maximum=maximum_bytes + overhead)
            if result.timed_out or result.overflowed or result.returncode != 0:
                raise _refuse("immutable image repository capture failed")
            with open(target, "rb") as handle:
                return capture_tar_file_map(
                    handle, prefix="m2", maximum_files=maximum_files,
                    maximum_bytes=maximum_bytes)


def _producer_lock_root() -> str:
    """One per-user directory for producer locks under the effective TMPDIR.

    An authority is minted for and refused outside one invoking UID, so the
    daemon this producer mutates is this user's own rootless daemon and the
    lock's collision domain is per user, per daemon fingerprint.  The former
    fixed shared-`/tmp` name was neither: it is one constant for the whole
    host, nothing unlinks it, and a 0600 leftover owned by an earlier root
    run made every later regular-user run die with EACCES inside `os.open`
    before the owner/mode check below could refuse honestly.  A foreign file
    left at that historical name is not read, chmod-ed, or removed.
    """
    root = os.path.join(tempfile.gettempdir(),
                        "r2t-epubcheck-image-" + str(os.getuid()))
    try:
        os.mkdir(root, 0o700)
    except FileExistsError:
        pass
    except OSError as exc:
        raise _refuse(
            f"cannot create the producer lock directory {root!r}: {exc}") from exc
    info = os.lstat(root)
    if stat.S_ISLNK(info.st_mode) or not stat.S_ISDIR(info.st_mode) \
            or info.st_uid != os.getuid() \
            or stat.S_IMODE(info.st_mode) != 0o700:
        raise _refuse("producer lock directory is not an owned 0700 directory")
    return root


@contextlib.contextmanager
def producer_lock(daemon_fingerprint: str):
    digest = _full_sha256(daemon_fingerprint, "daemon fingerprint")
    path = os.path.join(_producer_lock_root(), digest + ".lock")
    flags = os.O_RDWR | os.O_CREAT | getattr(os, "O_CLOEXEC", 0) \
        | getattr(os, "O_NOFOLLOW", 0)
    fd = os.open(path, flags, 0o600)
    try:
        info = os.fstat(fd)
        if not stat.S_ISREG(info.st_mode) or info.st_uid != os.getuid() \
                or stat.S_IMODE(info.st_mode) != 0o600:
            raise _refuse("producer lock is not one owner-private regular file")
        try:
            fcntl.flock(fd, fcntl.LOCK_EX | fcntl.LOCK_NB)
        except BlockingIOError as exc:
            raise _refuse("another EPUBCheck image producer holds this daemon") from exc
        yield
    finally:
        os.close(fd)


